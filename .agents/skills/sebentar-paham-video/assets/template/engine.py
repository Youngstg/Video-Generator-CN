 d=ImageDraw.Draw(im);lines=subtitle_lines(c['text']);yy=1584 if len(lines)==2 else 1619
 f=font(55,weight=650);widths=[f.getlength(x) for x in lines];pw=int(max(widths)+56);ph=76*len(lines)+10
 plate=Image.new('RGBA',(pw,ph),(0,0,0,0));ImageDraw.Draw(plate).rounded_rectangle((0,0,pw-1,ph-1),34,fill=rgb(T['bg'])+(205,))
 im.paste(plate,(int(540-pw/2),yy-8),plate)
 k=None;words=c.get('words')
 if words:
  k=-1
  for j,w in enumerate(words):
   if now>=w[1]-.02:k=j
  if k<0:k=None
 dim=blendcol(T['ink'],T['bg'],.30);idx=0;placed=[]
 for j,line in enumerate(lines):
  toks=line.split();x0=540-widths[j]/2
  for m,tok in enumerate(toks):
   placed.append((x0+f.getlength(' '.join(toks[:m])+(' ' if m else '')),yy+j*76,f.getlength(tok),tok,idx+m))
  idx+=len(toks)
 for px,py,wd,tok,gi in placed:
  if k is not None and gi==k:d.rounded_rectangle((px-11,py+1,px+wd+11,py+68),18,fill=T['soft'])
 for px,py,wd,tok,gi in placed:
  d.text((int(px),int(py)),tok,font=f,fill=T['ink'] if (k is None or gi<=k) else dim,anchor='lt')
 if LAYOUT is not None:LAYOUT.append(dict(kind='text',role='subtitle',text=c['text'],scene=i,box=(int(540-max(widths)/2),yy,int(540+max(widths)/2),yy+ph-10)))

