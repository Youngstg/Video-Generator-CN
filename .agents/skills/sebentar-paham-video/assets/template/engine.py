 if widest>width:raise LayoutError(f'Word {max(words,key=f.getlength)!r} is wider than {width:.0f}px at {n}px. Use a shorter word or a wider area.')
 def greedy(lim):
  rows=[];cur=''
  for w in words:
   t=(cur+' '+w).strip()
   if cur and f.getlength(t)>lim:rows.append(cur);cur=w
   else:cur=t
  rows.append(cur);return rows
