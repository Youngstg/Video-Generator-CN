# ---------------------------------------------------------------- layout lint
def _inter(a,b):return max(0,min(a[2],b[2])-max(a[0],b[0]))*max(0,min(a[3],b[3])-max(a[1],b[1]))
def _area(a):return max(1,(a[2]-a[0])*(a[3]-a[1]))
def _contains(o,i,m=0):return o[0]-m<=i[0] and o[1]-m<=i[1] and o[2]+m>=i[2] and o[3]+m>=i[3]

def check_layout(items):
 """Rules that catch text leaving its box, the canvas or the caption zone. Returns (severity,rule,item,detail)."""
 out=[];texts=[x for x in items if x['kind']=='text'];boxes=[x for x in items if x['kind']=='box' and x['box'][2]-x['box'][0]<1000]
 objs=[x for x in items if x['kind']=='object']
 for a in texts:
  x1,y1,x2,y2=a['box'];role=a['role']
  if x1<HARD[0] or x2>HARD[1] or y1<0 or y2>H:out.append(('error','outside_canvas',a,f'text spans x {x1}..{x2}, y {y1}..{y2}; the canvas is 0..1080 and the hard margin is {HARD[0]}..{HARD[1]}'))
  elif role!='brand' and (x1<SAFE[0] or x2>SAFE[1]):out.append(('warning','outside_safe_area',a,f'text spans x {x1}..{x2}; keep text inside {SAFE[0]}..{SAFE[1]}'))
  if role not in ('subtitle','brand') and _inter(a['box'],(0,CAPTION_ZONE[0],W,CAPTION_ZONE[1]))>0:out.append(('error','covers_caption_zone',a,f'text reaches y {y1}..{y2}; y {CAPTION_ZONE[0]}..{CAPTION_ZONE[1]} is reserved for subtitles'))
  for b in boxes:
   if not _inter(a['box'],b['box']):continue
   bw,bh=b['box'][2]-b['box'][0],b['box'][3]-b['box'][1]
   if _contains(b['box'],a['box']):
    if not _contains(b['box'],a['box'],-6):out.append(('warning','tight_padding',a,f'text is within 6px of its box edge {b["box"]}'))
   elif _contains(a['box'],b['box']):continue
   elif bw>=(x2-x1)*.5 and bh>=(y2-y1)*.9:out.append(('error','text_crosses_box',a,f'text {a["box"]} sticks out of box {b["box"]}; enlarge the box, wrap/shorten the text, or use chip()/box_text()'))
  for o in objs:
   if role not in ('header','brand','subtitle') and _inter(a['box'],o['box'])>.25*_area(a['box']):out.append(('warning','text_over_object',a,f'label overlaps an illustrated object {o["box"]}; move it clear of the drawing'))
 for j,a in enumerate(texts):
  for b in texts[j+1:]:
   if a['role']=='subtitle' or b['role']=='subtitle':continue
   if _inter(a['box'],b['box'])>.1*min(_area(a['box']),_area(b['box'])):out.append(('error','text_overlaps_text',a,f'{a["text"]!r} overlaps {b["text"]!r}'))
 for o in objs:
  if o['box'][0]<-5 or o['box'][2]>W+5 or o['box'][3]>CAPTION_ZONE[1] or o['box'][1]<480:out.append(('warning','object_off_stage',o,f'object {o["box"]} leaves the stage (x 0..1080, y 480..{CAPTION_ZONE[1]})'))
  elif _inter(o['box'],(0,CAPTION_ZONE[0]+30,W,CAPTION_ZONE[1]))>0:out.append(('warning','object_in_caption_zone',o,f'object reaches y {o["box"][3]}; subtitles will cover it'))
 return out

def lint(key,captions=False):
 """Render representative frames with the layout recorder on and fail on any overflow."""
 global LAYOUT
 configure(key,captions);qa=P/'qa';qa.mkdir(exist_ok=True)
 errors=[];warnings=[];seen=set();shots={}
 for i in range(7):
  dur=TIMELINE[i]['duration'] if captions else SERIES[key]['minimums'][i]
  times=[x for x in (1.3,3.0,5.0,7.0) if x<dur-.3] or [min(1.3,dur-.3)]
  if captions:
   cs=[c for c in CUES if c['scene']==i];start=TIMELINE[i]['start']
   times+=[((c['start']+c['end'])/2)-start for c in cs]
  for t in times:
   LAYOUT=[]
   try:im=frame(i,t,False) if captions else art(i,t,{'duration':dur})
   except LayoutError as ex:
    LAYOUT=None;sig=(i,'does_not_fit',str(ex),())
    if sig not in seen:seen.add(sig);errors.append(dict(scene=i+1,t=round(t,2),rule='does_not_fit',text='',box=[],detail=str(ex)))
    break
   finally:items=LAYOUT;LAYOUT=None
   for sev,rule,it,detail in check_layout(items):
    sig=(i,rule,it.get('text','') or tuple(int(v)//40 for v in it['box']))
    if sig in seen:continue
    seen.add(sig);row=dict(scene=i+1,t=round(t,2),rule=rule,text=it.get('text',''),box=list(it['box']),detail=detail)
    (errors if sev=='error' else warnings).append(row)
    if sev=='error' and i not in shots:
     shot=im.copy();dd=ImageDraw.Draw(shot)
     for r2 in [x for x in errors if x['scene']==i+1]:dd.rectangle(r2['box'],outline='#FF0033',width=5)
     shots[i]=shot
  if not captions:
   bare,bg=bare_art(i,min(6,dur-.5));diff=(np.abs(np.asarray(bare,np.int16)-np.asarray(bg,np.int16)).sum(2)>30)[480:1560]
   ys,xs=np.where(diff)
   if len(xs)==0:errors.append(dict(scene=i+1,t=6,rule='empty_stage',text='',box=[],detail='the illustration draws nothing visible'))
   else:
    fh=(ys.max()-ys.min())/1080;fw=(xs.max()-xs.min())/950;cy=(ys.max()+ys.min())/2+480
    if abs(cy-1040)>190:warnings.append(dict(scene=i+1,t=6,rule='off_centre',text='',box=[int(xs.min()),int(ys.min())+480,int(xs.max()),int(ys.max())+480],detail=f'illustration is centred at y={cy:.0f}; the stage centre is ~1040. Move/enlarge it so the lower stage is not empty'))
    if fh<.40 and fw<.85:warnings.append(dict(scene=i+1,t=6,rule='small_subject',text='',box=[int(xs.min()),int(ys.min())+480,int(xs.max()),int(ys.max())+480],detail=f'illustration fills {fw:.0%} of the stage width and {fh:.0%} of its height; enlarge the subject (aim for half to two-thirds of the stage)'))
 name=f'{key}_layout{"_captions" if captions else ""}'
 for i,shot in shots.items():save_image(shot.resize((540,960)),qa/f'{name}_scene{i+1}.png')
 report=dict(key=key,mode='captions' if captions else 'artwork',ok=not errors,errors=errors,warnings=warnings)
 (qa/(name+'.json')).write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
 for r2 in errors:print(f'LAYOUT ERROR scene {r2["scene"]} @{r2["t"]}s [{r2["rule"]}] {r2["text"]!r}: {r2["detail"]}',flush=True)
 for r2 in warnings:print(f'layout warning scene {r2["scene"]} [{r2["rule"]}] {r2["text"]!r}: {r2["detail"]}',flush=True)
 print(f'LAYOUT {"FAILED" if errors else "OK"}: {len(errors)} errors, {len(warnings)} warnings ({report["mode"]})',flush=True)
 return not errors


def render(key,i):
 configure(key);dur=TIMELINE[i]['duration'];n=round(dur*FPS)
 final=P/key/f'scene{i}.mp4';temp=final.with_suffix('.part.mp4')
 proc=subprocess.Popen(['ffmpeg','-y','-v','error','-f','rawvideo','-pixel_format','rgb24','-video_size','1080x1920','-framerate','30','-i','-','-an','-c:v','libx264','-preset','ultrafast','-crf','18','-pix_fmt','yuv420p','-threads','2',str(temp)],stdin=subprocess.PIPE)
 try:
  for j in range(n):proc.stdin.write(frame(i,j/FPS).tobytes())
 finally:
  proc.stdin.close()
  status=proc.wait()
 if status:raise RuntimeError(f'Scene encoder failed: {status}')
 probe=json.loads(subprocess.check_output(['ffprobe','-v','error','-select_streams','v:0','-show_entries','stream=nb_frames','-of','json',str(temp)]))
 if int(probe['streams'][0]['nb_frames'])!=n:raise RuntimeError('Incomplete scene export')
 temp.replace(final);print('SCENE READY',key,i,'9:16',flush=True)


